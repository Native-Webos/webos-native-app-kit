"""Write third_party/licenses/libdovi-crates.txt: the licence of every crate linked into libdovi.

    tools/libdovi-licences.py [--check]

Reads `cargo metadata` for third_party/libdovi on the webOS target and walks the normal (not build or
dev) dependencies from wnk-dovi, skipping proc-macro crates (they run in the compiler and are not
linked). Each crate gets its SPDX expression and the text of its licence files from the cargo
registry. Rust's standard library, also linked, is listed with the MIT and Apache-2.0 texts from the
toolchain. --check exits 1 when the committed file differs from what would be written.
"""
import json
import os
import subprocess
import sys

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(KIT, "third_party", "libdovi", "Cargo.toml")
OUT = os.path.join(KIT, "third_party", "licenses", "libdovi-crates.txt")
TARGET = "armv7-unknown-linux-gnueabi"


def licence_files(directory):
    names = sorted(n for n in os.listdir(directory)
                   if n.upper().startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE")) and
                   os.path.isfile(os.path.join(directory, n)))
    found = [(n, os.path.join(directory, n)) for n in names]
    sub = os.path.join(directory, "LICENSES")  # REUSE layout (crc-catalog)
    if os.path.isdir(sub):
        found += [(f"LICENSES/{n}", os.path.join(sub, n)) for n in sorted(os.listdir(sub))]
    return [(n, open(path, encoding="utf-8", errors="replace").read().strip()) for n, path in found]


def main():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", MANIFEST,
         "--filter-platform", TARGET], cwd=KIT))
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    linked, todo = set(), [root]
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            if not any(k["kind"] is None for k in dep["dep_kinds"]):
                continue
            pkg = packages[dep["pkg"]]
            if any("proc-macro" in t["kind"] for t in pkg["targets"]):
                continue
            if dep["pkg"] not in linked:
                linked.add(dep["pkg"])
                todo.append(dep["pkg"])
    out = ["Crates linked into the kit's libdovi (third_party/libdovi, cmake/LibDovi.cmake), generated by",
           "tools/libdovi-licences.py. Each is used under the licence named; where an expression offers a",
           "choice (\"MIT OR Apache-2.0\"), the kit uses it under MIT.", ""]
    for pid in sorted(linked, key=lambda i: (packages[i]["name"], packages[i]["version"])):
        p = packages[pid]
        out += ["=" * 100, f"{p['name']} {p['version']}  ({p.get('license') or 'see files'})",
                f"{p.get('repository') or ''}", "=" * 100]
        files = licence_files(os.path.dirname(p["manifest_path"]))
        if not files:
            sys.exit(f"{p['name']} {p['version']}: no licence file in its crate")
        for name, text in files:
            out += [f"--- {name}", text, ""]
    sysroot = subprocess.check_output(["rustc", "--print", "sysroot"], text=True).strip()
    lic = os.path.join(sysroot, "share", "doc", "rust", "licenses")
    out += ["=" * 100, "Rust standard library (std, core, alloc)  (MIT OR Apache-2.0)",
            "https://github.com/rust-lang/rust", "=" * 100]
    for name in ("MIT.txt", "Apache-2.0.txt"):
        out += [f"--- {name}", open(os.path.join(lic, name), encoding="utf-8").read().strip(), ""]
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit(f"{OUT} is out of date: run tools/libdovi-licences.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"{OUT}: {len(linked)} crates + std")


if __name__ == "__main__":
    main()
